import { existsSync, mkdirSync, readFileSync, symlinkSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { describe, expect, it } from 'vitest';
import { newId } from '@sa/core';
import {
  UP_SEGMENT,
  assertWithinWorkspace,
  generateOriginalSourcePath,
  generateWorkPath,
  normalizeSourceName,
  writeWorkFile,
} from '../src/policy/paths';
import { catchError, useTmpDir } from './helpers';

const tmp = useTmpDir();

const code = (fn: () => unknown) => (catchError(fn) as { code: string }).code;

describe('generateWorkPath', () => {
  it('builds <version_id>/<layer>/<file_id>.<ext> inside the workspace', () => {
    const ws = tmp();
    const versionId = newId();
    const fileId = newId();
    expect(generateWorkPath(ws, { versionId, layer: 'unpacked', fileId })).toEqual({
      relPath: `${versionId}/unpacked/${fileId}.js`,
      absPath: join(ws, versionId, 'unpacked', `${fileId}.js`),
    });
    expect(generateWorkPath(ws, { versionId, layer: 'raw', fileId, kind: 'sourcemap' }).relPath).toBe(`${versionId}/raw/${fileId}.map`);
    expect(generateWorkPath(ws, { versionId, layer: 'raw', fileId, kind: 'html' }).relPath).toBe(`${versionId}/raw/${fileId}.html`);
  });

  it('accepts only ULIDs generated by sa-core as path components', () => {
    const ws = tmp();
    for (const bad of ['../../etc', 'abc', '', `${newId()}/x`, newId().toLowerCase()]) {
      expect(code(() => generateWorkPath(ws, { versionId: bad, layer: 'raw', fileId: newId() }))).toBe('INVALID_INPUT');
      expect(code(() => generateWorkPath(ws, { versionId: newId(), layer: 'raw', fileId: bad }))).toBe('INVALID_INPUT');
    }
  });

  it('rejects unknown layers and kinds, and sends original layer to its own generator', () => {
    const ws = tmp();
    const ids = { versionId: newId(), fileId: newId() };
    expect(code(() => generateWorkPath(ws, { ...ids, layer: '../x' as 'raw' }))).toBe('INVALID_INPUT');
    expect(code(() => generateWorkPath(ws, { ...ids, layer: 'raw', kind: 'har' as 'js' }))).toBe('INVALID_INPUT');
    expect(code(() => generateWorkPath(ws, { ...ids, layer: 'original' }))).toBe('INVALID_INPUT');
  });
});

describe('normalizeSourceName', () => {
  it.each([
    ['webpack:///./src/App.vue?vue&type=script&lang=ts', 'src/App.vue'],
    ['webpack://my-app/./src/index.js', 'my-app/src/index.js'],
    ['file:///home/dev/project/src/a.ts', 'home/dev/project/src/a.ts'],
    ['/abs/path/b.js', 'abs/path/b.js'],
    ['src\\win\\c.js', 'src/win/c.js'],
    ['./src/./d.js#frag', 'src/d.js'],
    ['src/x/../e.js', 'src/e.js'],
    ['../../etc/passwd', `${UP_SEGMENT}/${UP_SEGMENT}/etc/passwd`],
    ['a/../../b.js', `${UP_SEGMENT}/b.js`],
    ['webpack:///../node_modules/react/index.js', `${UP_SEGMENT}/node_modules/react/index.js`],
    ['src/bad\u0000name\n.js', 'src/bad_name_.js'],
  ])('%j -> %j', (input, expected) => {
    expect(normalizeSourceName(input)).toBe(expected);
  });

  it('rejects names with no usable file path', () => {
    for (const bad of ['', '.', '..', 'webpack:///', '?vue', '../..', '/']) {
      expect(code(() => normalizeSourceName(bad))).toBe('INVALID_INPUT');
    }
  });

  it('rejects path segments longer than the filesystem allows', () => {
    expect(code(() => normalizeSourceName(`src/${'a'.repeat(256)}.js`))).toBe('INVALID_INPUT');
    expect(normalizeSourceName(`src/${'a'.repeat(252)}.js`)).toHaveLength(4 + 255);
  });
});

describe('generateOriginalSourcePath', () => {
  it('keeps the source structure under <version_id>/original/<map_file_id>/', () => {
    const ws = tmp();
    const versionId = newId();
    const mapFileId = newId();
    const p = generateOriginalSourcePath(ws, { versionId, mapFileId, sourceName: 'webpack:///../../../../etc/passwd' });
    expect(p.relPath).toBe(`${versionId}/original/${mapFileId}/${UP_SEGMENT}/${UP_SEGMENT}/${UP_SEGMENT}/${UP_SEGMENT}/etc/passwd`);
    expect(p.absPath.startsWith(join(ws, versionId, 'original', mapFileId))).toBe(true);
  });

  it('validates the ids', () => {
    expect(code(() => generateOriginalSourcePath(tmp(), { versionId: '..', mapFileId: newId(), sourceName: 'a.js' }))).toBe('INVALID_INPUT');
  });
});

describe('assertWithinWorkspace', () => {
  it('accepts paths inside the workspace and resolves relative ones against it', () => {
    const ws = tmp();
    expect(assertWithinWorkspace(ws, 'a/b.js')).toBe(join(ws, 'a', 'b.js'));
    expect(assertWithinWorkspace(ws, join(ws, 'a'))).toBe(join(ws, 'a'));
    expect(assertWithinWorkspace(ws, '..foo/x')).toBe(join(ws, '..foo', 'x'));
  });

  it('rejects lexical escapes, including sibling directories sharing a prefix', () => {
    const ws = tmp();
    for (const bad of ['../x', 'a/../../x', '/etc/passwd', `${ws}-evil/x`]) {
      expect(code(() => assertWithinWorkspace(ws, bad))).toBe('POLICY_DENIED');
    }
  });

  it('rejects escapes through symbolic links', () => {
    const ws = tmp();
    const outside = tmp();
    symlinkSync(outside, join(ws, 'link-dir'));
    symlinkSync(join(outside, 'target.js'), join(ws, 'link-file.js'));
    writeFileSync(join(outside, 'target.js'), 'x');
    expect(code(() => assertWithinWorkspace(ws, 'link-dir/new/file.js'))).toBe('POLICY_DENIED');
    expect(code(() => assertWithinWorkspace(ws, 'link-file.js'))).toBe('POLICY_DENIED');
  });

  it('requires the workspace to exist', () => {
    expect(code(() => assertWithinWorkspace(join(tmp(), 'missing'), 'a.js'))).toBe('INVALID_INPUT');
  });
});

describe('writeWorkFile', () => {
  it('writes bytes, creating parent directories, and overwrites regenerable files', () => {
    const ws = tmp();
    const rel = generateWorkPath(ws, { versionId: newId(), layer: 'pretty', fileId: newId() }).relPath;
    const abs = writeWorkFile(ws, rel, Buffer.from('first'));
    writeWorkFile(ws, rel, new Uint8Array([0xef, 0xbb, 0xbf, 0x61]));
    expect(readFileSync(abs)).toEqual(Buffer.from([0xef, 0xbb, 0xbf, 0x61]));
  });

  it('refuses absolute paths and escapes', () => {
    const ws = tmp();
    expect(code(() => writeWorkFile(ws, join(ws, 'a.js'), Buffer.from('x')))).toBe('INVALID_INPUT');
    expect(code(() => writeWorkFile(ws, '../escape.js', Buffer.from('x')))).toBe('POLICY_DENIED');
    expect(existsSync(join(ws, '..', 'escape.js'))).toBe(false);
  });

  it('does not follow a symbolic link at the final path, even one pointing inside the workspace', () => {
    const ws = tmp();
    mkdirSync(join(ws, 'dir'));
    writeFileSync(join(ws, 'dir', 'real.js'), 'keep');
    symlinkSync(join(ws, 'dir', 'real.js'), join(ws, 'dir', 'alias.js'));
    expect(code(() => writeWorkFile(ws, 'dir/alias.js', Buffer.from('overwrite')))).toBe('IO_ERROR');
    expect(readFileSync(join(ws, 'dir', 'real.js'), 'utf8')).toBe('keep');
  });
});
